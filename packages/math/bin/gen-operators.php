#!/usr/bin/env php
<?php

declare(strict_types=1);

/*
 * Generates resources/operators.php from the W3C MathML Core specification, Appendix B.2
 * "Operator Dictionary (human-readable)". Usage:
 *
 *   curl -sL https://www.w3.org/TR/mathml-core/ -o mathml-core.html
 *   php bin/gen-operators.php mathml-core.html
 *
 * The output is keyed by "char|form". Spaces are converted from em to 1/18 em. The spec text is
 * W3C document-licensed; only the table of facts is extracted.
 */

$source = $argv[1] ?? null;
if ($source === null || ! is_file($source)) {
    fwrite(STDERR, "usage: php bin/gen-operators.php <mathml-core.html>\n");
    exit(1);
}

$html = file_get_contents($source);
if ($html === false) {
    fwrite(STDERR, "cannot read {$source}\n");
    exit(1);
}
$version = preg_match('#This version:</dt>\s*<dd>\s*<a[^>]*href="([^"]+)"#', $html, $vm) ? $vm[1] : 'unknown version';
$start = strpos($html, 'id="operator-dictionary-table"');
$end = $start === false ? false : strpos($html, '</table>', $start);
if ($start === false || $end === false) {
    fwrite(STDERR, "operator dictionary table not found in {$source}\n");
    exit(1);
}

preg_match_all('#<tr>(.*?)</tr>#s', substr($html, $start, $end - $start), $rows);

$entries = [];
foreach ($rows[1] as $row) {
    preg_match_all('#<td>(.*?)</td>#s', $row, $cells);
    $c = array_map(static fn (string $s): string => trim(html_entity_decode(strip_tags($s), ENT_QUOTES | ENT_HTML5, 'UTF-8')), $cells[1]);
    if (count($c) < 6 || ! preg_match('/U\+([0-9A-F]+)$/', $c[0], $m)) {
        continue;
    }
    $char = mb_chr((int) hexdec($m[1]), 'UTF-8');
    $form = $c[2];
    $props = preg_split('/\s+/', $c[5]) ?: [];
    $entries[$char . '|' . $form] = [
        'form' => $form,
        'lspace' => (int) round((float) $c[3] * 18),
        'rspace' => (int) round((float) $c[4] * 18),
        'stretchy' => in_array('stretchy', $props, true),
        'symmetric' => in_array('symmetric', $props, true),
        'largeop' => in_array('largeop', $props, true),
        'movablelimits' => in_array('movablelimits', $props, true),
        'fence' => in_array('fence', $props, true),
    ];
}

ksort($entries);

$out = "<?php\n\ndeclare(strict_types=1);\n\n"
    . "// Generated by bin/gen-operators.php from the W3C MathML Core operator dictionary (Appendix B.2),\n"
    . "// snapshot {$version}\n"
    . "// Do not edit. Spaces are in 1/18 em. Keys are \"char|form\".\n\nreturn [\n";
foreach ($entries as $key => $e) {
    $fields = [];
    foreach ($e as $k => $v) {
        $fields[] = "'{$k}' => " . (is_bool($v) ? ($v ? 'true' : 'false') : (is_int($v) ? (string) $v : var_export($v, true)));
    }
    $out .= '    ' . var_export($key, true) . ' => [' . implode(', ', $fields) . "],\n";
}
$out .= "];\n";

file_put_contents(__DIR__ . '/../resources/operators.php', $out);
fwrite(STDOUT, count($entries) . " operators written\n");
